""" Variables = A container for a value (string, integer, float, boolean)
                A Variable behaves as if it was the value it contains."""

'''STRINGS'''
first_name = "paarth" # This is a string type variable. Strings are a series of characters. 
food = "pizza"
email = "paarthkantharia@gmail.com"

print(first_name) # This prints [paarth] the value of first_name variable.
print("first_name") #adding string inside the print statement just named us print the term [first_name] instead of the value of the variable [paarth]
print(f'hi, {first_name}') # We can print our varariale with other words with the help of a [f'{}] f string.
print(f'You like {food}')
print(f'This is your email - {email}')